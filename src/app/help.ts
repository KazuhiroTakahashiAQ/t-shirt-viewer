/** Set the titles of the static controls. */
export function applyStaticTips(root: ParentNode = document) {
  const set = (el: Element | null, tip: string | undefined) => {
    if (!el || !tip) return
    const target = el instanceof HTMLInputElement && el.parentElement instanceof HTMLLabelElement ? el.parentElement : el
    ;(target as HTMLElement).title = tip
  }
  root.querySelectorAll<HTMLElement>('[data-cmd]').forEach((el) => set(el, CMD_TIPS[el.dataset.cmd!]))
  root.querySelectorAll<HTMLInputElement>('input[data-opt]').forEach((el) => set(el, OPT_TIPS[el.dataset.opt!]))
  root.querySelectorAll<HTMLInputElement>('input[data-opt3d]').forEach((el) => set(el, OPT3D_TIPS[el.dataset.opt3d!]))
  root.querySelectorAll<HTMLInputElement>('input[data-panel]').forEach((el) => set(el, ID_TIPS[`panel:${el.dataset.panel}`]))
  root.querySelectorAll<HTMLInputElement>('input[name="section-mode"]').forEach((el) => set(el, ID_TIPS[`mode:${el.value}`]))
  root.querySelectorAll<HTMLElement>('.tab[data-tab]').forEach((el) => set(el, ID_TIPS[`tab:${el.dataset.tab}`]))
  root.querySelectorAll<HTMLElement>('[data-scroll]').forEach((el) => set(el, ID_TIPS[`scroll:${el.dataset.scroll}`]))
  root.querySelectorAll<HTMLElement>('.menu-title').forEach((el) => set(el, ID_TIPS[`menu:${(el.textContent ?? '').replace(/\(.*$/, '')}`]))
  for (const [id, tip] of Object.entries(ID_TIPS)) if (!id.includes(':')) set(root.querySelector(`#${id}`), tip)
}
